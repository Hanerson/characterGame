// 更新版块帖子数量
initialPosts.forEach(post => {
    const cat = forumCategories.find(c => c.id === post.category);
    if (cat) cat.topicCount++;
});

/**
 * 按版块筛选帖子
 */
export const getPostsByCategory = (categoryId) => {
    if (!categoryId || categoryId === 'all') return initialPosts;
    return initialPosts.filter(p => p.category === categoryId);
};

/**
 * 按时段筛选帖子
 */
export const getPostsByEpoch = (epoch) => {
    if (!epoch || epoch === 'all') return initialPosts;
    return initialPosts.filter(p => p.epoch === epoch);
};

/**
 * 搜索帖子（全文搜索标题和内容）
 */
export const searchPosts = (query) => {
    if (!query || query.trim() === '') return initialPosts;
    const lower = query.toLowerCase();
    return initialPosts.filter(p =>
        p.title.toLowerCase().includes(lower) ||
        p.content.toLowerCase().includes(lower) ||
        p.author.toLowerCase().includes(lower)
    );
};

/**
 * 获取热门帖子（回复数最多的前N篇）
 */
export const getHotPosts = (n = 10) => {
    return [...initialPosts].sort((a, b) => b.replies - a.replies).slice(0, n);
};

/**
 * 获取最新帖子
 */
export const getRecentPosts = (n = 10) => {
    return [...initialPosts].sort((a, b) => b.date.localeCompare(a.date)).slice(0, n);
};

/**
 * 获取用户的全部帖子
 */
export const getUserPosts = (username) => {
    return initialPosts.filter(p => p.author === username);
};
